/**
 * コマンドバーの「読みがな」検索。
 *
 * 【なぜ要るのか】(2026-09-02 / BACKLOG「読みがな検索は別項目」の回収)
 * コマンドバーの当たり判定は**書いてある文字そのもの**でしか行っていない
 * (`commandScore.ts` の `matchScore` / `commandFuzzy.ts` の `fuzzyScore`)。
 * ところが日本語の入力は **IME で かな を打っている途中**が必ず挟まる。
 * 「うりあげ」と打った時点でラベル「売上台帳」には 1 文字も重ならないので、
 * **変換を確定するまで一覧が空になる**。0 件画面まで一瞬出る。
 * 「請求書」を出したいのに「せいきゅうしょ」では何も出ない、が毎回起きていた。
 *
 * 【やり方】読みを**足すだけ**にする
 * ラベル/説明文から**ひらがなの読み**を作り、**かなで打った語だけ**をそこにも
 * 当てにいく。書いてある文字での当たり方は 1 点も変えない (足すだけ)。
 * 読みで当たった語は **+1 点**＝「説明文にだけ当たった」と同じいちばん弱い扱いで、
 * **書いてある文字で当たったものを追い抜かない**。
 *
 * 【辞書について・正直に】
 * 形態素解析は入れない (辞書だけで数百 KB になる。コマンドバーの語彙は
 * 下の 130 語ほどで足りる)。**辞書に無い漢字は読みを持たない**＝
 * ナレッジのタイトルやタスク名のような**動的な項目はかなでは当たらない**。
 * ここは嘘をつかず、当たらないものは当たらないままにしてある。
 */

/** カタカナ → ひらがな (長音符「ー」はそのまま) */
export function kataToHira(text: string): string {
  return text.replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));
}

