const WORDS_LONGEST_FIRST = Object.keys(WORD_READINGS).sort((a, b) => b.length - a.length);

/**
 * 読みがな文字列を作る。
 * ・辞書にある語 → ひらがなの読みへ
 * ・カタカナ → ひらがな (レポート → れぽーと)
 * ・英数字 → 小文字のまま
 * ・辞書に無い漢字 → **そのまま残す**（かなのクエリとは決して重ならないので害が無い）
 */
export function toReading(text: string): string {
  let out = text;
  for (const w of WORDS_LONGEST_FIRST) {
    if (out.includes(w)) out = out.split(w).join(WORD_READINGS[w]);
  }
  return kataToHira(out).toLowerCase();
}

/**
 * 「かなで打っている」語かどうか。
 * 1 文字だと当たりすぎる (「か」で山ほど出る) ので **2 文字以上**を条件にする。
 */
export function isKanaPart(part: string): boolean {
  return part.length >= 2 && /^[ぁ-ゖァ-ヺー]+$/.test(part);
}

/** 打った語を読み合わせ用に整える (カタカナで打たれても拾う) */
export function normalizeKanaPart(part: string): string {
  return kataToHira(part).toLowerCase();
}

/** 読みがなの側に当たるか。かなで打った語のときだけ true になりうる。 */
export function readingHit(part: string, reading: string | undefined): boolean {
  if (!reading || !isKanaPart(part)) return false;
  return reading.includes(normalizeKanaPart(part));
}
