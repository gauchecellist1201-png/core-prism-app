// ============================================================
// ink — 「面の色」から「読める文字色」を作る
//
// ★2026-08-02 実測の事故 (本番 375px・明るいテーマ):
//   ブリーフの根拠チップ「Stripe」「LINE配信」が 2.03:1、
//   クレジット残の「あと 998」が 1.75:1、
//   Stripe の失敗理由 (＝どう直せばいいかを書いてある唯一の文) が 1.06:1。
//   どれも「カードの面に使う色を、そのまま文字の色にも使っていた」ことが原因。
//   面は淡くていいが、文字は濃くないと読めない。役割が違うので色も分ける。
//
// 色がペルソナやプランで実行時に決まる箇所は CSS 変数で固定できないため、
// 「その色を、テーマの反対方向へ一定量だけ寄せる」式を共有する。
//   明るいテーマ → 黒へ 55%   暗いテーマ → 白へ 45%   (index.css の --ink-*)
// テーマを切り替えた瞬間に CSS 側だけで追従するので、再レンダリングは不要。
//
// 面 (background / border) には従来どおり元の色をそのまま使ってよい。
// ============================================================

/**
 * アクセント色を、いまのテーマで読める文字色に変換する。
 * @param accent '#34D399' などの色。CSS が解釈できる色ならなんでもよい
 */
export function readableInk(accent: string): string {
  return `color-mix(in srgb, ${accent}, var(--ink-toward) var(--ink-amount))`;
}

/**
 * 面(背景)に使う淡い色。元の色に alpha を掛けたもの。
 * `${accent}12` のような 8桁hex 連結はhex以外の色で壊れるので、こちらを使う。
 */
export function inkSurface(accent: string, percent: number): string {
  return `color-mix(in srgb, ${accent} ${percent}%, transparent)`;
}
