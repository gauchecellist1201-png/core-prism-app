// 料金の入口 — 発注の形をひとつ選ばせる (2026-08-23 新設)。
//
// 設計の理由:
//   従来は料金セクションの先頭に TRIAL の詳細カード (仕様8行・理由・含む/含まない) が
//   いきなり来ていた。1枚で1画面を使い切るため、スマホでは3プランの金額を並べて
//   比べる画面が最後まで現れず、「いくらなのか」が分からないまま離脱する。
//   先に (1) 発注の形 (2) 3つの金額 (3) 何が違うか を渡し、詳細はその後に置く。
//
//   金額をスイッチのラベル自体に載せる。「単発 / 月額」だけのラベルでは、
//   押してみるまで価格帯が分からず、選ぶ理由にならない。
// ------------------------------------------------------------
