// ------------------------------------------------------------
// 初回限定価格 (2026-08-24 新設・オーナー指示)
//
// 直したかった食い違い:
//   20秒1本の価格が ¥49,800 の1つしか存在せず、ヒーローにもその金額だけが出ていた。
//   読む人はこれを「1本あたりの通常価格」として受け取るので、月額(月4本 ¥228,000)を見た瞬間に
//   「1本ずつ4本頼めば ¥199,200 で済むのに、月額は3万円高い」という計算が成立してしまう。
//   実際には ¥49,800 は初めてのお取引にかぎった価格であり、毎月この価格で受け続けられるものではない。
//   よって 20秒1本の通常価格 ¥89,800 を正面に出し、¥49,800 はそこからの初回限定価格として示す。
//
//   結果として、価格の大小関係が全プランで一方向に揃う:
//     1本ずつ (20秒 ¥89,800) ＞ 月額4本 (1本 ¥57,000) ＞ 月額8本 (¥49,750) ＞ 月額12本 (¥45,667)
//   「続けるほど1本が安くなる」が、どこを読んでも矛盾しない状態になる。
//
// 数字を大きく見せない:
//   ¥89,800 → ¥49,800 は 44%OFF であって 50%OFF ではない。「半額」「50%OFF」と書くと
//   誰でも引き算できる嘘になり、価格全体の信用を落とす。割引率は計算値をそのまま出す。
//
// 限定の作り方:
//   「残り◯枠」のような、こちらで検証できないカウンターは作らない。
//   実際に守れる条件 (1社1本・毎月の受付社数) だけを書く。
// ------------------------------------------------------------
// ------------------------------------------------------------
// 開設記念価格 (2026-08-24 新設・オーナー指示)
//
// STANDARD / PREMIUM にも、通常価格からの割引として金額を出す。
//
// 「通常価格」の書き方について (景品表示法・二重価格表示):
//   過去に売った実績のない金額を「通常価格」として打ち消し線で見せると、
//   有利誤認表示にあたるおそれがある (最近相当期間の販売実績が要る)。
//   そこでここでは ¥192,000 / ¥385,000 を「過去の価格」ではなく
//   「この期限を過ぎたら実際に適用する価格」として設定し、注記も未来形で書く。
//   つまり運用としては値上げ予告であり、期限が来たら
//     (a) 実際にこの価格へ改定する か (b) until を延ばす
//   のどちらかを必ず決める必要がある。
//
//   決め忘れても嘘が残らないように、until を過ぎた場合は表示側 (FilmTab) が
//   打ち消し線と「◯%OFF」を自動的に消し、現行価格だけを出す
//   (Stripe の Price は ¥128,000 / ¥298,000 のままなので、金額の食い違いは起きない)。
// ------------------------------------------------------------
