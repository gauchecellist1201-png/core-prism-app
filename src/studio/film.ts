/** 比較表の1行。値の並びは FILM_PLANS の並びと同じ */
export type MatrixRow = { label: string; values: string[]; emphasis?: boolean };

/** 3プランの仕様を1つの表に組み直す。
    手で表を書くと、FILM_PLANS の仕様を直したときに必ず片方だけ古くなるので、
    行は FILM_PLANS[0] のラベルから作り、各プランはラベルで引く
    (プランごとに項目が増減しても、無い項目は「—」になるだけで表は壊れない)。 */
export function planMatrix(): MatrixRow[] {
  const rows: MatrixRow[] = FILM_PLANS[0].spec.map(s => ({
    label: s.label,
    values: FILM_PLANS.map(p => p.spec.find(x => x.label === s.label)?.value ?? '—'),
  }));
  rows.push({ label: '初稿まで', values: FILM_PLANS.map(p => p.delivery) });
  rows.push({ label: '広告への二次利用', values: FILM_PLANS.map(p => p.adUse), emphasis: true });
  return rows;
}

