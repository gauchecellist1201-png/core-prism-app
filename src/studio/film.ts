/** 単発で同じ本数を作った場合との差額。価格改定時に手で直す箇所を作らないため実データから計算する */
export function monthlySavings(plan: MonthlyPlan) {
  // 基準は「20秒1本の通常価格 ¥89,800」。
  //   初回限定価格 (¥49,800) を基準にすると、毎月は出せない価格で毎月の総額を計算することになり、
  //   実際には受けられない条件を比較の土台にしてしまう。必ず listPriceYen を使う。
  const trial = FILM_PLANS.find(p => p.id === 'trial');
  const unitYen = trial?.listPriceYen ?? trial?.priceYen ?? 0;
  const oneOffTotal = unitYen * plan.count;
  const diff = oneOffTotal - plan.priceYen;
  // 切り上げて大きく見せない。実際より控えめな整数%だけを出す
  const percent = oneOffTotal > 0 ? Math.floor((diff / oneOffTotal) * 100) : 0;
  return { oneOffTotal, diff, percent, yearlyDiff: diff * 12 };
}

