/** 期限内かどうか。過ぎていたら割引の表示自体を消す (期限切れの「◯%OFF」を残さない) */
export function isCampaignLive(now: Date = new Date()): boolean {
  // 「10月31日のご発注分まで」なので、その日の終わりまでを含める
  return now.getTime() <= new Date(`${CAMPAIGN.until}T23:59:59+09:00`).getTime();
}

/** 割引率。切り捨てて、実際より大きく見せない (44.5% → 44%) */
export const offPercent = (listYen: number, priceYen: number) =>
  listYen > 0 ? Math.floor(((listYen - priceYen) / listYen) * 100) : 0;

